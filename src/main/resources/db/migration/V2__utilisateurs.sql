-- Comptes des personnes qui utilisent l'API : gérants et livreurs.
-- On se connecte avec son numéro de téléphone (+237…), plus courant que l'e-mail au Cameroun.
-- Le mot de passe n'est JAMAIS stocké en clair : seulement son empreinte BCrypt.

create table utilisateur (
    id           bigint generated by default as identity primary key,
    nom          varchar(120) not null,
    telephone    varchar(20)  not null unique,
    mot_de_passe varchar(100) not null,
    role         varchar(20)  not null,
    actif        boolean      not null default true,
    cree_le      timestamp with time zone not null
);

-- Pour retrouver vite « mes livraisons » d'un livreur.
create index idx_livraison_livreur on livraison (livreur_telephone);
