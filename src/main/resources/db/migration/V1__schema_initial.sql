-- Schéma initial : produits, commandes, lignes de commande, livraisons et leur historique.
-- Compatible PostgreSQL et H2 (mode PostgreSQL).
-- Les montants sont en FCFA : nombres entiers, sans centimes.

create table produit (
    id          bigint generated by default as identity primary key,
    nom         varchar(120)  not null,
    description varchar(1000),
    prix_fcfa   bigint        not null check (prix_fcfa > 0),
    stock       integer       not null check (stock >= 0),
    actif       boolean       not null default true,
    cree_le     timestamp with time zone not null,
    version     bigint        not null default 0
);

create table commande (
    id                bigint generated by default as identity primary key,
    reference         varchar(20) unique,
    client_nom        varchar(120) not null,
    telephone         varchar(20)  not null,
    quartier          varchar(120) not null,
    ville             varchar(80)  not null,
    indications       varchar(500),
    statut            varchar(20)  not null,
    total_fcfa        bigint       not null,
    motif_annulation  varchar(300),
    cree_le           timestamp with time zone not null
);

create index idx_commande_statut on commande (statut);

create table ligne_commande (
    id                 bigint generated by default as identity primary key,
    commande_id        bigint  not null references commande (id) on delete cascade,
    produit_id         bigint  not null references produit (id),
    quantite           integer not null check (quantite > 0),
    prix_unitaire_fcfa bigint  not null
);

create index idx_ligne_commande_commande on ligne_commande (commande_id);

create table livraison (
    id                bigint generated by default as identity primary key,
    commande_id       bigint      not null unique references commande (id),
    statut            varchar(20) not null,
    livreur_nom       varchar(120),
    livreur_telephone varchar(20),
    cree_le           timestamp with time zone not null,
    maj_le            timestamp with time zone not null
);

create index idx_livraison_statut on livraison (statut);

create table evenement_livraison (
    id             bigint generated by default as identity primary key,
    livraison_id   bigint      not null references livraison (id) on delete cascade,
    statut         varchar(20) not null,
    commentaire    varchar(300),
    date_evenement timestamp with time zone not null
);

create index idx_evenement_livraison on evenement_livraison (livraison_id);
